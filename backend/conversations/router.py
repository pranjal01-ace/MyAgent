"""
Conversations Domain Router.

Defines HTTP REST endpoints for text chat interactions, SSE token streaming,
and session history management with Ace AI.
"""

import json
import logging
from typing import Optional
from fastapi import APIRouter, HTTPException, Query, status
from fastapi.responses import StreamingResponse

from backend.conversations.schemas import ChatRequest, ChatResponse
from backend.conversations.service import chat_service
from backend.conversations.repository import conversation_repository

logger = logging.getLogger("ace.conversations.router")

router = APIRouter(tags=["conversations"])


# ==============================================================================
# Chat Execution Endpoints
# ==============================================================================

@router.post(
    "/chat",
    response_model=ChatResponse,
    summary="Send single-turn chat prompt"
)
async def chat_endpoint(req: ChatRequest):
    """
    Execute a single-turn conversation prompt with Portgas D. Ace AI.

    Handles intent classification, optional tool execution, prompt caching,
    and concurrent voice speech synthesis.
    """
    user_text = req.message.strip()
    if not user_text:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )

    result = await chat_service.execute_chat(
        message=user_text,
        session_id=req.session_id or "default",
        speak=req.speak if req.speak is not None else True
    )

    return ChatResponse(
        user_message=result["user_message"],
        response=result["response"],
        tool_executed=result.get("tool_executed"),
        state=result.get("state", "idle"),
        cached=result.get("cached", False)
    )


@router.post(
    "/chat/stream",
    summary="Stream chat tokens with real-time TTS"
)
async def chat_stream_endpoint(req: ChatRequest):
    """
    Stream conversation tokens in real-time using Server-Sent Events (SSE).

    Integrates concurrent sentence-level TTS synthesis so audio playback
    begins while remaining tokens are actively being generated by Ollama.
    """
    user_text = req.message.strip()
    if not user_text:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Message cannot be empty."
        )

    async def event_generator():
        async for event in chat_service.stream_chat(
            message=user_text,
            session_id=req.session_id or "default",
            speak=req.speak if req.speak is not None else True
        ):
            yield f"data: {json.dumps(event)}\n\n"

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"
        }
    )


# ==============================================================================
# Conversation History Management Endpoints
# ==============================================================================

@router.get(
    "/chat/history",
    summary="Get recent conversation turns"
)
async def get_history_endpoint(
    session_id: str = Query("default", max_length=64, description="Session identifier"),
    limit: int = Query(20, ge=1, le=100, description="Max messages to retrieve")
):
    """Retrieve chronologically ordered recent messages for a session."""
    messages = conversation_repository.get_recent_messages(
        session_id=session_id,
        limit=limit
    )
    return {
        "session_id": session_id,
        "messages": messages,
        "count": len(messages)
    }


@router.delete(
    "/chat/history",
    summary="Clear session conversation history"
)
async def clear_history_endpoint(
    session_id: str = Query("default", max_length=64, description="Session identifier")
):
    """Clear all chat turns for a specific session."""
    deleted = conversation_repository.clear_conversation(session_id=session_id)
    return {
        "success": True,
        "session_id": session_id,
        "deleted_count": deleted
    }


# ==============================================================================
